def draw_arrow(draw, start, end, color, width=5):
    draw.line([start, end], fill=color, width=width)
    x1, y1 = start
    x2, y2 = end
    import math

    angle = math.atan2(y2 - y1, x2 - x1)
    head_len = 18
    for delta in (2.6, -2.6):
        x3 = x2 - head_len * math.cos(angle + delta)
        y3 = y2 - head_len * math.sin(angle + delta)
        draw.line([(x2, y2), (x3, y3)], fill=color, width=width)


