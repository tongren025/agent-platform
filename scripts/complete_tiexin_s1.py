def build_new_cards() -> list[dict[str, Any]]:
    new_cards: list[dict[str, Any]] = []
    for scene_id, scene in EXTRA_SCENES.items():
        new_cards.append(make_scene_card(scene_id, scene))

    for episode, data in EPISODES.items():
        new_cards.append(make_script_card(episode, data))
        for g_index, unit in enumerate(data["beats"], 1):
            if unit is None:
                continue
            for shot_index in range(3):
                new_cards.append(
                    make_storyboard_card(
                        episode,
                        g_index,
                        shot_index,
                        unit,
                    )
                )
            new_cards.append(make_image_card(episode, g_index, unit))
            new_cards.append(make_video_card(episode, g_index, unit))
    return new_cards


def render_season_script(cards: list[dict[str, Any]]) -> str:
    scripts = [
        card
        for card in cards
        if card.get("stage") == "script" and isinstance(card.get("episode"), int)
    ]
    scripts.sort(key=lambda card: card["episode"])
    header = (
        "# 《铁心恋人》第一季 · 12集制作剧本\n\n"
        "> 生产口径：12集 × 90秒｜每集6个G单元｜每G 15秒｜每G拆A/B/C三个5秒生成段｜竖屏9:16  \n"
        "> 视觉：电影级真人现代都市科幻；女主始终拥有行动与决定权，男主完成“服从工具→自主选择”的人格弧。\n\n"
        "## 全季结构\n\n"
        "| 集数 | 标题 | 核心推进 |\n"
        "|---:|---|---|\n"
    )
    table_rows = []
    for episode, data in EPISODES.items():
        table_rows.append(
            f"| EP{episode:02d} | {data['title']} | {data['quote']} |"
        )
    body = [header + "\n".join(table_rows)]
    body.extend(card["content"] for card in scripts)
    return "\n\n---\n\n".join(body) + "\n"


def main() -> None:
    existing_cards = json.loads(CARDS_PATH.read_text(encoding="utf-8"))
    legacy_storyboards = [
        card
        for card in existing_cards
        if (
            card.get("stage") == "storyboard"
            and card.get("metadata", {}).get("sub_segments") == 3
            and not card.get("metadata", {}).get("segment")
            and not card.get("images")
            and not card.get("metadata", {}).get("image_reviews")
        )
    ]
    legacy_storyboard_ids = {
        card.get("card_id")
        for card in legacy_storyboards
        if card.get("card_id")
    }
    existing_cards = [
        card
        for card in existing_cards
        if card.get("card_id") not in legacy_storyboard_ids
    ]
    # 2026-07-25 曾短暂调整 CITY_ROAD 卡标题；标题属于旧版逻辑键，
    # 因此在恢复稳定标题时显式清理该脚本生成的迁移副本，避免留下重复场景卡。
    existing_cards = [
        card
        for card in existing_cards
        if not (
            card.get("stage") == "setting"
            and card.get("title") == "场景：城市高架、服务通道与离城公路"
            and card.get("metadata", {}).get("scene_id") == "CITY_ROAD"
        )
    ]
    by_key = index_cards_by_key(existing_cards, source="现有卡片")
    new_cards = build_new_cards()
    index_cards_by_key(new_cards, source="待生成卡片")
    added = 0
    updated = 0

    for new_card in new_cards:
        key = card_key(new_card)
        if key in by_key:
            old_card = by_key[key]
            runtime_keys = {
                "active_image",
                "image_reviews",
                "review_verdict",
                "reviewed_at",
                "reviewed_by",
                "media_status",
                "generated_segments",
                "episode_media_status",
                "generation_spec_fingerprint",
                "video_review_status",
                "video_review_fingerprints",
                "video_reviewed_at",
                "video_reviewed_by",
            }
            old_spec_metadata = {
                metadata_key: metadata_value
                for metadata_key, metadata_value in old_card.get(
                    "metadata",
                    {},
                ).items()
                if metadata_key not in runtime_keys
            }
            if (
                old_card["content"] != new_card["content"]
                or old_spec_metadata != new_card["metadata"]
                or old_card.get("prompts", []) != new_card["prompts"]
            ):
                runtime_metadata = {
                    runtime_key: runtime_value
                    for runtime_key, runtime_value in old_card.get(
                        "metadata",
                        {},
                    ).items()
                    if runtime_key in runtime_keys
                }
                new_card["metadata"] = {
                    **new_card["metadata"],
                    **runtime_metadata,
                }
                new_card["card_id"] = old_card["card_id"]
                new_card["created_at"] = old_card.get("created_at", STAMP)
                new_card["images"] = list(old_card.get("images", []))
                new_card["videos"] = list(old_card.get("videos", []))
                new_card["assignee"] = old_card.get("assignee", "")
                if new_card["images"] or runtime_metadata:
                    new_card["status"] = old_card.get(
                        "status",
                        new_card["status"],
                    )
                index = existing_cards.index(old_card)
                existing_cards[index] = new_card
                by_key[key] = new_card
                updated += 1
        else:
            existing_cards.append(new_card)
            by_key[key] = new_card
            added += 1

    CARDS_PATH.write_text(
        json.dumps(existing_cards, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    SCRIPT_PATH.write_text(render_season_script(existing_cards), encoding="utf-8")
    print(
        json.dumps(
            {
                "cards_total": len(existing_cards),
                "cards_added": added,
                "cards_updated": updated,
                "legacy_storyboards_removed": len(legacy_storyboards),
                "season_script": str(SCRIPT_PATH),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
