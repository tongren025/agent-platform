# 少数 G 单元包含明确的跨场景切镜。这里按“一镜一卡”声明真实场景和出镜
# 角色，避免整组沿用同一个场景/角色集合。键中的第三项为 0/1/2 段索引。
SEGMENT_SCENE_OVERRIDES: dict[tuple[int, int, int], str] = {
    (4, 6, 2): "HANYU_TOWER",
    (8, 6, 2): "HANYU_TOWER",
}

SEGMENT_CHARACTER_OVERRIDES: dict[
    tuple[int, int, int],
    tuple[str, ...],
] = {
    (4, 6, 0): ("R2",),
    (4, 6, 1): ("R2",),
    (4, 6, 2): ("R3",),
    (8, 6, 0): ("R1", "R2"),
    (8, 6, 1): ("R1", "R2"),
    (8, 6, 2): ("R3",),
}


def scene_for_segment(
    episode: int,
    g_index: int,
    segment_index: int,
    unit: dict[str, Any],
) -> str:
    """返回单镜真实场景；未声明切镜时沿用 G 单元场景。"""
    return SEGMENT_SCENE_OVERRIDES.get(
        (episode, g_index, segment_index),
        unit["scene"],
    )


def characters_for_segment(
    episode: int,
    g_index: int,
    segment_index: int,
    unit: dict[str, Any],
) -> list[str]:
    """返回单镜实际出镜角色，避免把切走后的角色继续塞入参考图。"""
    override = SEGMENT_CHARACTER_OVERRIDES.get(
        (episode, g_index, segment_index)
    )
    return list(override or unit["characters"])


